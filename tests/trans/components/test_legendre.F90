PROGRAM TEST_LEGENDRE

USE COMPONENT_TEST_UTILS
USE PARKIND_ECTRANS, ONLY: JPRB, JPRD, JPIB
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
USE TPM_DISTR, ONLY: D
USE TPM_DIM, ONLY: R
USE TPM_FIELDS, ONLY: F
USE TPM_GEOMETRY, ONLY: G
USE LTINV_MOD, ONLY: PREPARE_LTINV, LTINV, LTINV_HANDLE
USE LTDIR_MOD, ONLY: PREPARE_LTDIR, LTDIR, LTDIR_HANDLE
USE LEINV_MOD, ONLY: LEINV_STRIDES
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR, MAKE_BUFFERED_ALLOCATOR, INSTANTIATE_ALLOCATOR
USE GROWING_ALLOCATOR_MOD, ONLY: GROWING_ALLOCATION_TYPE, DESTROY_GROWING_ALLOCATOR

IMPLICIT NONE

TYPE(BUFFERED_ALLOCATOR) :: ALLOCATOR
TYPE(GROWING_ALLOCATION_TYPE) :: STORAGE
TYPE(LTINV_HANDLE) :: INVERSE
TYPE(LTDIR_HANDLE) :: DIRECT
REAL(JPRB), ALLOCATABLE :: SPECTRAL(:,:), OUTPUT(:,:)
REAL(JPRB), POINTER :: SYMMETRIC(:), ANTISYMMETRIC(:), WEIGHTED_S(:), WEIGHTED_A(:)
REAL(JPRD), POINTER :: SYMMETRIC0(:), ANTISYMMETRIC0(:), WEIGHTED_S0(:), WEIGHTED_A0(:)
INTEGER :: STRIDE, STRIDE0, SIZE0, JM, M, JLAT, FIRST_LAT, FAILURES
INTEGER(JPIB) :: BUFFER_SIZE, POS
REAL(JPRD) :: WEIGHT, ERROR, SCALE

CALL INIT_TEST()
ALLOCATE(SPECTRAL(NFIELDS,D%NSPEC2), OUTPUT(NFIELDS,D%NSPEC2))
CALL RANDOM_NUMBER(SPECTRAL)
SPECTRAL = 2.0_JPRB*SPECTRAL-1.0_JPRB
! Scalar spherical harmonics have real m=0 coefficients. Imaginary m=0 is not represented.
DO JM=1,D%NUMP
  IF (D%MYMS(JM) == 0) SPECTRAL(:,D%NASM0(0)+1:D%NASM0(0)+2*R%NSMAX+1:2) = 0.0_JPRB
ENDDO
ALLOCATOR = MAKE_BUFFERED_ALLOCATOR()
NULLIFY(STORAGE%PTR)
STORAGE%FREE_FUNCS_SZ = 0
INVERSE = PREPARE_LTINV(ALLOCATOR,0,NFIELDS,.FALSE.,.FALSE.,.FALSE.)
DIRECT = PREPARE_LTDIR(ALLOCATOR,NFIELDS,0)
CALL INSTANTIATE_ALLOCATOR(ALLOCATOR,STORAGE)
CALL LTINV(ALLOCATOR,INVERSE,0,NFIELDS,PSPSCALAR=SPECTRAL, &
  & ZOUTS=SYMMETRIC,ZOUTA=ANTISYMMETRIC,ZOUTS0=SYMMETRIC0,ZOUTA0=ANTISYMMETRIC0)
CALL LEINV_STRIDES(NFIELDS,IOUT_STRIDES0=STRIDE,IOUT_SIZE=BUFFER_SIZE,IOUT0_STRIDES0=STRIDE0,IOUT0_SIZE=SIZE0)
!$ACC WAIT(1)
!$ACC UPDATE HOST(SYMMETRIC,ANTISYMMETRIC,SYMMETRIC0,ANTISYMMETRIC0)
ALLOCATE(WEIGHTED_S(BUFFER_SIZE), WEIGHTED_A(BUFFER_SIZE), WEIGHTED_S0(SIZE0), WEIGHTED_A0(SIZE0))
WEIGHTED_S = 0.0_JPRB
WEIGHTED_A = 0.0_JPRB
WEIGHTED_S0 = 0.0_JPRD
WEIGHTED_A0 = 0.0_JPRD
! The transpose unpacker normally forms N+S and N-S, then applies Gaussian
! weights. Apply those quadrature weights here without involving MPI or FFTs.
DO JM=1,D%NUMP
  M = D%MYMS(JM)
  FIRST_LAT = R%NDGNH-G%NDGLU(M)+1
  DO JLAT=FIRST_LAT,R%NDGNH
    WEIGHT = 2.0_JPRD*F%RW(JLAT)
    IF (M == 0) THEN
      POS = (JLAT-1)*STRIDE0
      WEIGHTED_S0(POS+1:POS+NFIELDS) = WEIGHT*SYMMETRIC0(POS+1:POS+NFIELDS)
      WEIGHTED_A0(POS+1:POS+NFIELDS) = WEIGHT*ANTISYMMETRIC0(POS+1:POS+NFIELDS)
    ELSE
      POS = STRIDE*(D%OFFSETS_GEMM1(JM)+JLAT-FIRST_LAT)
      WEIGHTED_S(POS+1:POS+2*NFIELDS) = REAL(WEIGHT,JPRB)*SYMMETRIC(POS+1:POS+2*NFIELDS)
      WEIGHTED_A(POS+1:POS+2*NFIELDS) = REAL(WEIGHT,JPRB)*ANTISYMMETRIC(POS+1:POS+2*NFIELDS)
    ENDIF
  ENDDO
ENDDO
!$ACC DATA COPYIN(WEIGHTED_S,WEIGHTED_A,WEIGHTED_S0,WEIGHTED_A0)
CALL LTDIR(ALLOCATOR,DIRECT,WEIGHTED_S,WEIGHTED_A,WEIGHTED_S0,WEIGHTED_A0,NFIELDS,0,NFIELDS,PSPSCALAR=OUTPUT)
!$ACC END DATA
! Compare the original and recovered two-dimensional coefficient arrays.
FAILURES = COUNT(.NOT. IEEE_IS_FINITE(OUTPUT))+COUNT(.NOT. IEEE_IS_FINITE(SPECTRAL))
ERROR = MAX(0.0_JPRD,MAXVAL(ABS(REAL(OUTPUT,JPRD)-REAL(SPECTRAL,JPRD))))
SCALE = MAX(1.0_JPRD,MAXVAL(ABS(REAL(SPECTRAL,JPRD))))
CALL ASSERT_ERROR(ERROR,SCALE,FAILURES,256*REAL(EPSILON(0.0_JPRB),JPRD),'Legendre round trip')
DEALLOCATE(WEIGHTED_S,WEIGHTED_A,WEIGHTED_S0,WEIGHTED_A0)
CALL DESTROY_GROWING_ALLOCATOR(STORAGE)
CALL END_TEST('Legendre')
END PROGRAM
