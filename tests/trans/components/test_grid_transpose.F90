PROGRAM TEST_GRID_TRANSPOSE

USE COMPONENT_TEST_UTILS
USE PARKIND_ECTRANS, ONLY: JPRB, JPIM
USE TPM_DISTR, ONLY: D, NPRTRV, MYSETV
USE MPL_MODULE, ONLY: MPL_ALLREDUCE, MPL_ABORT
USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: INT8
USE TPM_TRANS, ONLY: NPROMA, NGPBLKS
USE TRGTOL_MOD, ONLY: PREPARE_TRGTOL, TRGTOL, TRGTOL_HANDLE
USE TRLTOG_MOD, ONLY: PREPARE_TRLTOG, TRLTOG, TRLTOG_HANDLE
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR, MAKE_BUFFERED_ALLOCATOR, INSTANTIATE_ALLOCATOR
USE GROWING_ALLOCATOR_MOD, ONLY: GROWING_ALLOCATION_TYPE, DESTROY_GROWING_ALLOCATOR

IMPLICIT NONE

TYPE(BUFFERED_ALLOCATOR) :: ALLOCATOR
TYPE(GROWING_ALLOCATION_TYPE) :: STORAGE
TYPE(TRGTOL_HANDLE) :: FORWARD
TYPE(TRLTOG_HANDLE) :: BACKWARD
REAL(JPRB), POINTER :: REEL(:)
REAL(JPRB), ALLOCATABLE :: INPUT(:,:,:), OUTPUT(:,:,:)
INTEGER(JPIM), ALLOCATABLE :: VSET(:)
INTEGER :: NF_FS, J, F, BLK, ACTIVE, NBYTES, FAILURES

! One wave set makes fields move between vertical sets, including empty ones.
CALL INIT_TEST(KWAVESETS=1)
ALLOCATE(VSET(NFIELDS))
VSET = [(MOD(J-1,NPRTRV)+1, J=1,NFIELDS)]
NF_FS = COUNT(VSET == MYSETV)
ALLOCATE(INPUT(NPROMA,NFIELDS,NGPBLKS), OUTPUT(NPROMA,NFIELDS,NGPBLKS))
DO BLK=1,NGPBLKS
  DO F=1,NFIELDS
    CALL RANDOM_VALUES(INPUT(:,F,BLK))
  ENDDO
ENDDO
OUTPUT = HUGE(0.0_JPRB)
ALLOCATOR = MAKE_BUFFERED_ALLOCATOR()
NULLIFY(STORAGE%PTR)
STORAGE%FREE_FUNCS_SZ = 0
FORWARD = PREPARE_TRGTOL(ALLOCATOR,NFIELDS,NF_FS)
BACKWARD = PREPARE_TRLTOG(ALLOCATOR,NF_FS,NFIELDS)
CALL INSTANTIATE_ALLOCATOR(ALLOCATOR, STORAGE)
CALL TRGTOL(ALLOCATOR,FORWARD,REEL,NF_FS,NFIELDS,0,NFIELDS,PGP=INPUT,KVSETSC=VSET)
CALL TRLTOG(ALLOCATOR,BACKWARD,REEL,NF_FS,NFIELDS,0,NFIELDS,PGP=OUTPUT,KVSETSC=VSET)
! Compare original and recovered array views directly, excluding NPROMA padding.
! Integer-byte comparison also checks the sign bit of zero.
FAILURES = 0
DO BLK=1,NGPBLKS
  ACTIVE = MIN(NPROMA,D%NGPTOT-(BLK-1)*NPROMA)
  NBYTES = ACTIVE*STORAGE_SIZE(0.0_JPRB)/8
  DO F=1,NFIELDS
    FAILURES = FAILURES+COUNT(TRANSFER(INPUT(:ACTIVE,F,BLK),[0_INT8],NBYTES) /= &
      & TRANSFER(OUTPUT(:ACTIVE,F,BLK),[0_INT8],NBYTES))
  ENDDO
ENDDO
CALL MPL_ALLREDUCE(FAILURES,'SUM')
IF (FAILURES /= 0) CALL MPL_ABORT('TRGTOL/TRLTOG bitwise round trip')
CALL DESTROY_GROWING_ALLOCATOR(STORAGE)
CALL END_TEST('grid transpose')
END PROGRAM
