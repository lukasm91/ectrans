MODULE CPU_COMPONENT_TEST_UTILS
USE PARKIND_ECTRANS, ONLY: JPIM, JPRB, JPRD, JPIB
USE MPL_MODULE, ONLY: MPL_INIT, MPL_NPROC, MPL_MYRANK, MPL_ALLREDUCE, MPL_ABORT, MPL_END
IMPLICIT NONE
INTEGER(JPIM) :: NFIELDS=7, NRANKS, RANK
INTEGER(JPIM), PARAMETER :: TRUNCATION=23
#include "setup_trans0.h"
#include "setup_trans.h"
#include "trans_end.h"
CONTAINS
SUBROUTINE INIT_TEST(FULL_GRID,WAVESETS)
USE TPM_TRANS, ONLY: NPROMA,NGPBLKS,NF_SC2,NF_SC3A,NF_SC3B,LVORGP,LDIVGP,LSCDERS,LUVDER,LATLON
USE TPM_DISTR, ONLY: D
LOGICAL, OPTIONAL, INTENT(IN) :: FULL_GRID
INTEGER, OPTIONAL, INTENT(IN) :: WAVESETS
INTEGER(JPIM) :: J,NW,LOENS(2*(TRUNCATION+1))
CHARACTER(32) :: ARG
IF (COMMAND_ARGUMENT_COUNT()>0) THEN
  CALL GET_COMMAND_ARGUMENT(1,ARG)
  READ(ARG,*) NFIELDS
ENDIF
CALL MPL_INIT
IF (NFIELDS<1) CALL MPL_ABORT('Invalid component field count')
NRANKS=MPL_NPROC()
RANK=MPL_MYRANK()
NW=NRANKS
IF (PRESENT(WAVESETS)) NW=WAVESETS
DO J=1,SIZE(LOENS)
  LOENS(J)=20+4*(MIN(J,SIZE(LOENS)+1-J)-1)
ENDDO
IF (PRESENT(FULL_GRID)) THEN
  IF (FULL_GRID) LOENS=4*(TRUNCATION+1)
ENDIF
CALL SETUP_TRANS0(KPRGPNS=NRANKS,KPRTRW=NW,LDSYNC_TRANS=.FALSE.)
CALL SETUP_TRANS(KSMAX=TRUNCATION,KDGL=SIZE(LOENS),KLOEN=LOENS,LDUSERPNM=.FALSE.)
NPROMA=7
NGPBLKS=(D%NGPTOT+NPROMA-1)/NPROMA
NF_SC2=0
NF_SC3A=0
NF_SC3B=0
LVORGP=.FALSE.
LDIVGP=.FALSE.
LSCDERS=.FALSE.
LUVDER=.FALSE.
LATLON=.FALSE.
END SUBROUTINE
SUBROUTINE FINISH(NAME,FAILURES)
CHARACTER(*), INTENT(IN) :: NAME
INTEGER(JPIB), INTENT(INOUT) :: FAILURES
CALL MPL_ALLREDUCE(FAILURES,CDOPER='SUM')
IF (FAILURES/=0) CALL MPL_ABORT('CPU component failed: '//NAME)
IF (RANK==1) WRITE(*,*) 'CPU component passed: '//NAME, ' fields/ranks=',NFIELDS,NRANKS
CALL TRANS_END
CALL MPL_END(LDMEMINFO=.FALSE.)
END SUBROUTINE
END MODULE
