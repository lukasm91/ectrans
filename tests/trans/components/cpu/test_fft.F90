PROGRAM TEST_FFT_CPU

USE PARKIND_ECTRANS, ONLY: JPRB, JPRD, JPIM
USE MPL_MODULE, ONLY: MPL_INIT, MPL_NPROC, MPL_MYRANK, MPL_ALLREDUCE, MPL_ABORT, MPL_END
USE TPM_DISTR, ONLY: D, MYSETW
USE TPM_GEOMETRY, ONLY: G
USE FTDIR_MOD, ONLY: FTDIR
USE FTINV_MOD, ONLY: FTINV
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE

IMPLICIT NONE

#include "setup_trans0.h"
#include "setup_trans.h"
#include "trans_end.h"

INTEGER(JPIM), PARAMETER :: TRUNCATION=23, NLATITUDES=2*(TRUNCATION+1)
INTEGER(JPIM) :: NFIELDS, BATCH, NPROC, RANK, JL, LAT, N, KEPT, M, J, F, OFFSET, FAILURES
INTEGER(JPIM) :: LOENS(NLATITUDES)
REAL(JPRB), POINTER, CONTIGUOUS :: REEL(:,:)
REAL(JPRB), ALLOCATABLE :: EXPECTED(:,:)
REAL(JPRD) :: PI, PHASE, VALUE, A, B, REFERENCE, ERROR(2), SCALE, TOLERANCE
CHARACTER(32) :: ARG

NFIELDS=7
BATCH=0
IF (COMMAND_ARGUMENT_COUNT()>=1) THEN
  CALL GET_COMMAND_ARGUMENT(1,ARG)
  READ(ARG,*) NFIELDS
ENDIF
IF (COMMAND_ARGUMENT_COUNT()>=2) THEN
  CALL GET_COMMAND_ARGUMENT(2,ARG)
  READ(ARG,*) BATCH
ENDIF
CALL MPL_INIT
IF (NFIELDS<1 .OR. BATCH<0 .OR. BATCH>1) CALL MPL_ABORT('Invalid FFT component arguments')
NPROC=MPL_NPROC()
RANK=MPL_MYRANK()
DO J=1,NLATITUDES
  LOENS(J)=20+4*(MIN(J,NLATITUDES+1-J)-1)
ENDDO
CALL SETUP_TRANS0(KPRGPNS=NPROC,KPRTRW=NPROC,LDSYNC_TRANS=.FALSE.)
CALL SETUP_TRANS(KSMAX=TRUNCATION,KDGL=NLATITUDES,KLOEN=LOENS, &
  & LDUSERPNM=.FALSE.,LD_ALL_FFTW=BATCH==1)
ALLOCATE(REEL(NFIELDS,D%NLENGTF),EXPECTED(NFIELDS,D%NLENGTF))
REEL=0.0_JPRB
PI=ACOS(-1.0_JPRD)

! Synthesize only retained modes: FTDIR intentionally discards the spectral tail.
! Phase evaluation and reference coefficients are independent of the FFT backend.
DO JL=1,D%NDGL_FS
  LAT=D%NPTRLS(MYSETW)+JL-1
  N=G%NLOEN(LAT)
  KEPT=MIN(G%NMEN(LAT),N/2-1)
  OFFSET=D%NSTAGTF(JL)
  DO F=1,NFIELDS
    DO J=0,N-1
      VALUE=CONSTANT(F)
      DO M=1,KEPT
        CALL COEFFICIENTS(M,F,A,B)
        PHASE=2.0_JPRD*PI*REAL(MOD(M*J,N),JPRD)/REAL(N,JPRD)
        VALUE=VALUE+A*COS(PHASE)+B*SIN(PHASE)
      ENDDO
      REEL(F,OFFSET+J+1)=REAL(VALUE,JPRB)
    ENDDO
  ENDDO
ENDDO
EXPECTED=REEL
ERROR=0.0_JPRD
SCALE=MAX(1.0_JPRD,MAXVAL(ABS(REAL(EXPECTED,JPRD))))
FAILURES=0

DO JL=1,D%NDGL_FS
  CALL FTDIR(REEL,NFIELDS,JL)
  LAT=D%NPTRLS(MYSETW)+JL-1
  N=G%NLOEN(LAT)
  KEPT=MIN(G%NMEN(LAT),N/2-1)
  OFFSET=D%NSTAGTF(JL)
  DO F=1,NFIELDS
    DO M=0,G%NMEN(LAT)
      A=0.0_JPRD
      B=0.0_JPRD
      IF (M==0) THEN
        A=CONSTANT(F)
      ELSEIF (M<=KEPT) THEN
        CALL COEFFICIENTS(M,F,A,B)
        A=0.5_JPRD*A
        B=-0.5_JPRD*B
      ENDIF
      ! CPU FTDIR normalizes by N; packed coefficients are [Re(0),Im(0),...].
      CALL COMPARE(REAL(REEL(F,OFFSET+2*M+1),JPRD),A,ERROR(1))
      CALL COMPARE(REAL(REEL(F,OFFSET+2*M+2),JPRD),B,ERROR(1))
    ENDDO
  ENDDO
ENDDO

DO JL=1,D%NDGL_FS
  CALL FTINV(REEL,NFIELDS,JL)
  LAT=D%NPTRLS(MYSETW)+JL-1
  N=G%NLOEN(LAT)
  OFFSET=D%NSTAGTF(JL)
  DO J=1,N
    DO F=1,NFIELDS
      REFERENCE=REAL(EXPECTED(F,OFFSET+J),JPRD)
      CALL COMPARE(REAL(REEL(F,OFFSET+J),JPRD),REFERENCE,ERROR(2))
    ENDDO
  ENDDO
ENDDO

CALL MPL_ALLREDUCE(ERROR,CDOPER='MAX')
CALL MPL_ALLREDUCE(SCALE,CDOPER='MAX')
CALL MPL_ALLREDUCE(FAILURES,CDOPER='SUM')
TOLERANCE=64.0_JPRD*REAL(EPSILON(0.0_JPRB),JPRD)*SCALE
IF (RANK==1) THEN
  WRITE(*,*) 'CPU FFT fields, batched, ranks:',NFIELDS,BATCH,NPROC
  WRITE(*,*) 'Forward coefficient and round-trip maximum errors:',ERROR
  WRITE(*,*) 'Fixed 64*epsilon*scale tolerance:',TOLERANCE
ENDIF
IF (FAILURES/=0 .OR. ANY(ERROR>TOLERANCE)) CALL MPL_ABORT('CPU FFT component check failed')
DEALLOCATE(REEL,EXPECTED)
CALL TRANS_END
CALL MPL_END(LDMEMINFO=.FALSE.)

CONTAINS

FUNCTION CONSTANT(FIELD) RESULT(V)
  INTEGER, INTENT(IN) :: FIELD
  REAL(JPRD) :: V
  V=0.125_JPRD/REAL(FIELD+1,JPRD)
END FUNCTION

SUBROUTINE COEFFICIENTS(MODE,FIELD,COSINE,SINE)
  INTEGER, INTENT(IN) :: MODE,FIELD
  REAL(JPRD), INTENT(OUT) :: COSINE,SINE
  COSINE=SIN(0.31_JPRD*REAL(MODE+2*FIELD,JPRD))/REAL((MODE+1)**2,JPRD)
  SINE=COS(0.17_JPRD*REAL(2*MODE+FIELD,JPRD))/REAL((MODE+1)**2,JPRD)
END SUBROUTINE

SUBROUTINE COMPARE(ACTUAL,REFERENCE,MAX_ERROR)
  REAL(JPRD), INTENT(IN) :: ACTUAL,REFERENCE
  REAL(JPRD), INTENT(INOUT) :: MAX_ERROR
  IF (.NOT. IEEE_IS_FINITE(ACTUAL)) THEN
    FAILURES=FAILURES+1
  ELSE
    MAX_ERROR=MAX(MAX_ERROR,ABS(ACTUAL-REFERENCE))
  ENDIF
END SUBROUTINE

END PROGRAM
