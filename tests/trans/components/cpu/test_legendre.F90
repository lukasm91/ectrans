PROGRAM TEST_LEGENDRE_CPU
USE CPU_COMPONENT_TEST_UTILS
USE TPM_DISTR, ONLY: D,NPRTRW
USE TPM_TRANS, ONLY: FOUBUF,FOUBUF_IN
USE LTINV_MOD, ONLY: LTINV
USE LTDIR_MOD, ONLY: LTDIR
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
IMPLICIT NONE
REAL(JPRB), ALLOCATABLE :: INPUT(:,:),OUTPUT(:,:)
REAL(JPRD) :: ERROR,SCALE,TOLERANCE
INTEGER :: JM,M,N,I,F,P,LENGTH,SRC,DST,K,SZ
INTEGER(JPIB) :: FAILURES
! Full quadrature avoids reduced-grid polar truncation of arbitrary spectra.
CALL INIT_TEST(FULL_GRID=.TRUE.)
ALLOCATE(INPUT(NFIELDS,D%NSPEC2),OUTPUT(NFIELDS,D%NSPEC2))
INPUT=0.0_JPRB
OUTPUT=0.0_JPRB
DO JM=1,D%NUMP
  M=D%MYMS(JM)
  DO N=M,TRUNCATION
    I=D%NASM0(M)+2*(N-M)
    DO F=1,NFIELDS
      INPUT(F,I)=REAL(SIN(REAL(3*N+7*M+F,JPRD)),JPRB)
      IF (M/=0) INPUT(F,I+1)=REAL(COS(REAL(5*N+M+2*F,JPRD)),JPRB)
    ENDDO
  ENDDO
ENDDO
K=2*NFIELDS
SZ=MAX(1,K*MAX(D%NSTAGT0B(NPRTRW+1),D%NSTAGT1B(NPRTRW+1)))
ALLOCATE(FOUBUF_IN(SZ),FOUBUF(SZ))
FOUBUF_IN=0.0_JPRB
FOUBUF=0.0_JPRB
DO JM=1,D%NUMP
  M=D%MYMS(JM)
  CALL LTINV(M,JM,NFIELDS,0,NFIELDS,0,K,K,PSPSCALAR=INPUT)
ENDDO
! Transfer active peer blocks between the CPU stage layouts locally: no FFT,
! MPI transpose or scalar arithmetic is part of this Legendre identity.
DO P=1,NPRTRW
  LENGTH=K*D%NLTSFTB(P)
  SRC=K*D%NSTAGT0B(P)
  DST=K*D%NSTAGT1B(P)
  FOUBUF(DST+1:DST+LENGTH)=FOUBUF_IN(SRC+1:SRC+LENGTH)
ENDDO
DO JM=1,D%NUMP
  M=D%MYMS(JM)
  CALL LTDIR(M,JM,NFIELDS,0,NFIELDS,K,PSPSCALAR=OUTPUT)
ENDDO
FAILURES=0
ERROR=0.0_JPRD
SCALE=MAX(1.0_JPRD,MAXVAL(ABS(REAL(INPUT,JPRD))))
DO I=1,D%NSPEC2
  DO F=1,NFIELDS
    IF (.NOT. IEEE_IS_FINITE(OUTPUT(F,I))) THEN
      FAILURES=FAILURES+1
    ELSE
      ERROR=MAX(ERROR,ABS(REAL(OUTPUT(F,I),JPRD)-REAL(INPUT(F,I),JPRD)))
    ENDIF
  ENDDO
ENDDO
CALL MPL_ALLREDUCE(ERROR,CDOPER='MAX')
CALL MPL_ALLREDUCE(SCALE,CDOPER='MAX')
TOLERANCE=256.0_JPRD*REAL(EPSILON(0.0_JPRB),JPRD)*SCALE
IF (RANK==1) WRITE(*,*) 'CPU Legendre maximum error/tolerance:',ERROR,TOLERANCE
IF (ERROR>TOLERANCE) FAILURES=FAILURES+1
DEALLOCATE(FOUBUF,FOUBUF_IN)
CALL FINISH('Legendre',FAILURES)
END PROGRAM
