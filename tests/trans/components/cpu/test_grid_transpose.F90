PROGRAM TEST_GRID_TRANSPOSE_CPU
USE CPU_COMPONENT_TEST_UTILS
USE TPM_DISTR, ONLY: D,NPRTRV,MYSETV
USE TPM_TRANS, ONLY: NPROMA,NGPBLKS
USE TRGTOL_MOD, ONLY: TRGTOL
USE TRLTOG_MOD, ONLY: TRLTOG
USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: INT8
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_VALUE,IEEE_NEGATIVE_ZERO
IMPLICIT NONE
REAL(JPRB), ALLOCATABLE :: INPUT(:,:,:),OUTPUT(:,:,:),REEL(:,:)
INTEGER(JPIM), ALLOCATABLE :: VSET(:)
INTEGER :: J,F,B,ACTIVE,NBYTES,NLOCAL
INTEGER(JPIB) :: FAILURES
! One wave set exercises field redistribution, including empty local sets.
CALL INIT_TEST(WAVESETS=1)
ALLOCATE(VSET(NFIELDS))
VSET=[(MOD(J-1,NPRTRV)+1,J=1,NFIELDS)]
NLOCAL=COUNT(VSET==MYSETV)
ALLOCATE(INPUT(NPROMA,NFIELDS,NGPBLKS),OUTPUT(NPROMA,NFIELDS,NGPBLKS),REEL(NLOCAL,D%NLENGTF))
DO B=1,NGPBLKS
  DO F=1,NFIELDS
    DO J=1,NPROMA
      INPUT(J,F,B)=REAL(MOD(J+13*F+37*B+101*RANK,1024)-512,JPRB)/128.0_JPRB
    ENDDO
    INPUT(1,F,B)=IEEE_VALUE(0.0_JPRB,IEEE_NEGATIVE_ZERO)
  ENDDO
ENDDO
OUTPUT=HUGE(0.0_JPRB)
CALL TRGTOL(REEL,NLOCAL,NFIELDS,NFIELDS,VSET,PGP=INPUT)
CALL TRLTOG(REEL,NLOCAL,NFIELDS,NFIELDS,VSET,PGP=OUTPUT)
FAILURES=0
DO B=1,NGPBLKS
  ACTIVE=MIN(NPROMA,D%NGPTOT-(B-1)*NPROMA)
  NBYTES=ACTIVE*STORAGE_SIZE(0.0_JPRB)/8
  DO F=1,NFIELDS
    FAILURES=FAILURES+COUNT(TRANSFER(INPUT(:ACTIVE,F,B),[0_INT8],NBYTES) /= &
      & TRANSFER(OUTPUT(:ACTIVE,F,B),[0_INT8],NBYTES),KIND=JPIB)
  ENDDO
ENDDO
CALL FINISH('grid transpose (bitwise)',FAILURES)
END PROGRAM
