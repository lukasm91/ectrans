PROGRAM TEST_FOURIER_TRANSPOSE_CPU
USE CPU_COMPONENT_TEST_UTILS
USE TPM_DISTR, ONLY: D,NPRTRW
USE TRMTOL_MOD, ONLY: TRMTOL
USE TRLTOM_MOD, ONLY: TRLTOM
USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: INT8
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_VALUE,IEEE_NEGATIVE_ZERO
IMPLICIT NONE
REAL(JPRB), ALLOCATABLE :: INPUT(:),LAT0(:),LAT1(:),OUTPUT(:)
INTEGER :: J,P,N,K,SRC,DST,NBYTES
INTEGER(JPIB) :: FAILURES
CALL INIT_TEST()
K=2*NFIELDS
! Each direction has its own peer padding; keep native views for comparison.
N=MAX(1,K*MAX(D%NSTAGT0B(NPRTRW+1),D%NSTAGT1B(NPRTRW+1)))
ALLOCATE(INPUT(N),LAT0(N),LAT1(N),OUTPUT(N))
DO J=1,N
  INPUT(J)=REAL(MOD(J+101*RANK,2048)-1024,JPRB)/128.0_JPRB
ENDDO
DO P=1,NPRTRW
  IF (D%NLTSFTB(P)>0) INPUT(K*D%NSTAGT0B(P)+1)=IEEE_VALUE(0.0_JPRB,IEEE_NEGATIVE_ZERO)
ENDDO
LAT0=HUGE(0.0_JPRB)
LAT1=HUGE(0.0_JPRB)
OUTPUT=HUGE(0.0_JPRB)
CALL TRMTOL(INPUT,LAT0,K)
! Only bridge the two native peer-padding strides, without MPI or arithmetic.
DO P=1,NPRTRW
  J=D%MSTABF(P)
  N=K*D%NLTSGTB(P)
  SRC=K*D%NSTAGT0B(J)
  DST=K*D%NSTAGT1B(J)
  LAT1(DST+1:DST+N)=LAT0(SRC+1:SRC+N)
ENDDO
CALL TRLTOM(LAT1,OUTPUT,K)
FAILURES=0
DO P=1,NPRTRW
  N=K*D%NLTSFTB(P)
  SRC=K*D%NSTAGT0B(P)
  DST=K*D%NSTAGT1B(P)
  NBYTES=N*STORAGE_SIZE(0.0_JPRB)/8
  FAILURES=FAILURES+COUNT(TRANSFER(INPUT(SRC+1:SRC+N),[0_INT8],NBYTES) /= &
    & TRANSFER(OUTPUT(DST+1:DST+N),[0_INT8],NBYTES),KIND=JPIB)
ENDDO
CALL FINISH('Fourier transpose (bitwise)',FAILURES)
END PROGRAM
