MODULE COMPONENT_TEST_UTILS

USE PARKIND_ECTRANS, ONLY: JPIM, JPRB, JPRD
USE MPL_MODULE, ONLY: MPL_INIT, MPL_NPROC, MPL_MYRANK, MPL_ALLREDUCE, MPL_ABORT, MPL_END
USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: INT8

IMPLICIT NONE

PRIVATE
PUBLIC :: INIT_TEST, END_TEST, RANDOM_VALUES, ASSERT_BITS, ASSERT_ERROR, NFIELDS, NRANKS, RANK
INTEGER :: NFIELDS = 7, NRANKS, RANK

#include "setup_trans0.h"
#include "setup_trans.h"
#include "trans_end.h"

CONTAINS

SUBROUTINE INIT_TEST(KWAVESETS)
  USE TPM_TRANS, ONLY: NPROMA, NGPBLKS, NF_SC2, NF_SC3A, NF_SC3B, &
    & LVORGP, LDIVGP, LSCDERS, LUVDER, LATLON, GROWING_ALLOCATION
  USE TPM_DISTR, ONLY: D
  USE SET_RESOL_MOD, ONLY: SET_RESOL
  INTEGER, OPTIONAL, INTENT(IN) :: KWAVESETS
  INTEGER :: JWAVES, J, NS, IERR
  INTEGER, ALLOCATABLE :: SEED(:)
  INTEGER(JPIM) :: LOENS(48)
  CHARACTER(32) :: ARG

  CALL MPL_INIT
  NRANKS = MPL_NPROC()
  RANK = MPL_MYRANK()
  IF (COMMAND_ARGUMENT_COUNT() > 0) THEN
    CALL GET_COMMAND_ARGUMENT(1, ARG)
    READ(ARG, *, IOSTAT=IERR) NFIELDS
    IF (IERR /= 0) CALL MPL_ABORT('Invalid field count')
  ENDIF
  IF (NFIELDS < 1) CALL MPL_ABORT('Field count must be positive')
  JWAVES = NRANKS
  IF (PRESENT(KWAVESETS)) JWAVES = KWAVESETS
  CALL SETUP_TRANS0(KPRGPNS=NRANKS, KPRTRW=JWAVES, LDSYNC_TRANS=.FALSE.)
  ! Several even FFT lengths, symmetric about the equator. All represent m<=23.
  DO J=1,SIZE(LOENS)
    LOENS(J) = 96 + 4*MOD(MIN(J, SIZE(LOENS)+1-J), 3)
  ENDDO
  CALL SETUP_TRANS(KSMAX=23, KDGL=48, KLOEN=LOENS, LDUSEFLT=.FALSE., LDKEEPRPNM=.TRUE.)
  CALL SET_RESOL()
  NPROMA = 7
  NGPBLKS = (D%NGPTOT+NPROMA-1)/NPROMA
  NF_SC2 = 0
  NF_SC3A = 0
  NF_SC3B = 0
  LVORGP = .FALSE.
  LDIVGP = .FALSE.
  LSCDERS = .FALSE.
  LUVDER = .FALSE.
  LATLON = .FALSE.
  NULLIFY(GROWING_ALLOCATION%PTR)
  GROWING_ALLOCATION%FREE_FUNCS_SZ = 0
  CALL RANDOM_SEED(SIZE=NS)
  ALLOCATE(SEED(NS))
  SEED = [(1729 + 104729*RANK + 37*J, J=1,NS)]
  CALL RANDOM_SEED(PUT=SEED)
END SUBROUTINE

SUBROUTINE RANDOM_VALUES(VALUES)
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_VALUE, IEEE_NEGATIVE_ZERO
  REAL(JPRB), INTENT(OUT) :: VALUES(:)

  CALL RANDOM_NUMBER(VALUES)
  VALUES = 2.0_JPRB*VALUES-1.0_JPRB
  ! Numeric equality alone cannot detect a lost sign bit on zero.
  IF (SIZE(VALUES) > 0) VALUES(1) = IEEE_VALUE(0.0_JPRB, IEEE_NEGATIVE_ZERO)
END SUBROUTINE

SUBROUTINE ASSERT_BITS(A, B, MESSAGE)
  REAL(JPRB), INTENT(IN) :: A(:), B(:)
  CHARACTER(*), INTENT(IN) :: MESSAGE
  INTEGER :: NB, FAILURES

  IF (SIZE(A) /= SIZE(B)) CALL MPL_ABORT('Bit comparison shape mismatch')
  NB = SIZE(A)*STORAGE_SIZE(0.0_JPRB)/8
  FAILURES = COUNT(TRANSFER(A, [0_INT8], NB) /= TRANSFER(B, [0_INT8], NB))
  CALL MPL_ALLREDUCE(FAILURES, 'SUM')
  IF (FAILURES /= 0) THEN
    WRITE(*,*) TRIM(MESSAGE), ': differing bytes =', FAILURES
    CALL MPL_ABORT(MESSAGE)
  ENDIF
END SUBROUTINE

SUBROUTINE ASSERT_ERROR(LOCAL_ERROR,LOCAL_SCALE,LOCAL_FAILURES,TOLERANCE,MESSAGE)
  REAL(JPRD), INTENT(IN) :: LOCAL_ERROR, LOCAL_SCALE, TOLERANCE
  INTEGER, INTENT(IN) :: LOCAL_FAILURES
  CHARACTER(*), INTENT(IN) :: MESSAGE
  REAL(JPRD) :: ERROR, SCALE
  INTEGER :: FAILURES

  ERROR = LOCAL_ERROR
  SCALE = MAX(1.0_JPRD,LOCAL_SCALE)
  FAILURES = LOCAL_FAILURES
  CALL MPL_ALLREDUCE(FAILURES,'SUM')
  IF (FAILURES /= 0) CALL MPL_ABORT('Non-finite component result')
  CALL MPL_ALLREDUCE(ERROR,'MAX')
  CALL MPL_ALLREDUCE(SCALE,'MAX')
  IF (RANK == 1) WRITE(*,*) TRIM(MESSAGE), ': scaled max error =', ERROR/SCALE
  IF (ERROR > TOLERANCE*SCALE) CALL MPL_ABORT(MESSAGE)
END SUBROUTINE

SUBROUTINE END_TEST(NAME)
  CHARACTER(*), INTENT(IN) :: NAME

  IF (RANK == 1) WRITE(*,*) 'PASS: ', TRIM(NAME)
  CALL TRANS_END
  CALL MPL_END(LDMEMINFO=.FALSE.)
END SUBROUTINE

END MODULE
