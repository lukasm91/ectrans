PROGRAM TEST_FFT

USE COMPONENT_TEST_UTILS
USE PARKIND_ECTRANS, ONLY: JPRB, JPRD, JPIB
USE TPM_DISTR, ONLY: D, MYSETW
USE TPM_GEOMETRY, ONLY: G
USE TPM_DIM, ONLY: R
USE FTDIR_MOD, ONLY: PREPARE_FTDIR, FTDIR, FTDIR_HANDLE
USE FTINV_MOD, ONLY: PREPARE_FTINV, FTINV, FTINV_HANDLE
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR, MAKE_BUFFERED_ALLOCATOR, INSTANTIATE_ALLOCATOR, &
  & RESERVE, ALLOCATION_RESERVATION_HANDLE, GET_ALLOCATION, ASSIGN_PTR
USE GROWING_ALLOCATOR_MOD, ONLY: GROWING_ALLOCATION_TYPE, DESTROY_GROWING_ALLOCATOR
USE ISO_C_BINDING, ONLY: C_SIZE_T, C_SIZEOF
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE

IMPLICIT NONE

TYPE(BUFFERED_ALLOCATOR) :: ALLOCATOR
TYPE(GROWING_ALLOCATION_TYPE) :: STORAGE
TYPE(ALLOCATION_RESERVATION_HANDLE) :: INPUT_STORAGE
TYPE(FTDIR_HANDLE) :: FORWARD
TYPE(FTINV_HANDLE) :: BACKWARD
REAL(JPRB), POINTER :: BUFFER(:), REALSPACE(:), FOURIER(:)
REAL(JPRB), ALLOCATABLE :: EXPECTED(:), COS_COEFF(:), SIN_COEFF(:)
REAL(JPRD) :: PI, VALUE, PHASE, ERROR, SCALE
INTEGER :: JL, F, J, M, N, PITCH, KEPT, LATITUDE, FAILURES
INTEGER(JPIB) :: OFFSET

CALL INIT_TEST()
PI = ACOS(-1.0_JPRD)
ALLOCATOR = MAKE_BUFFERED_ALLOCATOR()
NULLIFY(STORAGE%PTR)
STORAGE%FREE_FUNCS_SZ = 0
INPUT_STORAGE = RESERVE(ALLOCATOR,INT(D%NLENGTF,C_SIZE_T)*NFIELDS*C_SIZEOF(0.0_JPRB),'FFT input')
FORWARD = PREPARE_FTDIR(ALLOCATOR,NFIELDS)
BACKWARD = PREPARE_FTINV(ALLOCATOR,NFIELDS)
CALL INSTANTIATE_ALLOCATOR(ALLOCATOR,STORAGE)
CALL ASSIGN_PTR(BUFFER,GET_ALLOCATION(ALLOCATOR,INPUT_STORAGE),1_C_SIZE_T, &
  & INT(D%NLENGTF,C_SIZE_T)*NFIELDS*C_SIZEOF(0.0_JPRB))
ALLOCATE(COS_COEFF(0:R%NSMAX), SIN_COEFF(0:R%NSMAX))
CALL RANDOM_VALUES(BUFFER)
! Only retained real Fourier modes can satisfy the round-trip identity after
! truncation. Synthesize them independently, then cast once to test precision.
DO JL=1,D%NDGL_FS
  LATITUDE = D%NPTRLS(MYSETW)+JL-1
  N = G%NLOEN(LATITUDE)
  KEPT = MIN(R%NSMAX,G%NMEN(LATITUDE),(N-1)/2)
  PITCH = D%NSTAGTF(JL+1)-D%NSTAGTF(JL)
  DO F=1,NFIELDS
    OFFSET = D%NSTAGTF(JL)*NFIELDS+(F-1)*PITCH
    CALL RANDOM_NUMBER(COS_COEFF)
    COS_COEFF = 2.0_JPRB*COS_COEFF-1.0_JPRB
    CALL RANDOM_VALUES(SIN_COEFF)
    DO J=1,N
      VALUE = REAL(COS_COEFF(0),JPRD)
      DO M=1,KEPT
        PHASE = 2.0_JPRD*PI*REAL(MOD(INT(M,JPIB)*INT(J-1,JPIB),INT(N,JPIB)),JPRD)/REAL(N,JPRD)
        VALUE = VALUE + (REAL(COS_COEFF(M),JPRD)*COS(PHASE) + &
          & REAL(SIN_COEFF(M),JPRD)*SIN(PHASE))/REAL(M+1,JPRD)
      ENDDO
      BUFFER(OFFSET+J) = REAL(VALUE,JPRB)
    ENDDO
  ENDDO
ENDDO
EXPECTED = BUFFER

!$ACC UPDATE DEVICE(BUFFER)
REALSPACE => BUFFER
CALL FTDIR(ALLOCATOR,FORWARD,REALSPACE,FOURIER,NFIELDS)
! Project onto the retained Fourier space, without gathering comparison vectors.
!$ACC WAIT(1)
!$ACC UPDATE HOST(FOURIER)
DO JL=1,D%NDGL_FS
  LATITUDE = D%NPTRLS(MYSETW)+JL-1
  N = G%NLOEN(LATITUDE)
  KEPT = MIN(R%NSMAX,G%NMEN(LATITUDE),N/2)
  PITCH = D%NSTAGTF(JL+1)-D%NSTAGTF(JL)
  DO F=1,NFIELDS
    OFFSET = D%NSTAGTF(JL)*NFIELDS+(F-1)*PITCH
    IF (KEPT < N/2) FOURIER(OFFSET+2*(KEPT+1)+1:OFFSET+2*(N/2+1)) = 0.0_JPRB
  ENDDO
ENDDO
!$ACC UPDATE DEVICE(FOURIER)
CALL FTINV(ALLOCATOR,BACKWARD,FOURIER,REALSPACE,NFIELDS)
!$ACC WAIT(1)
!$ACC UPDATE HOST(REALSPACE)
ERROR = 0.0_JPRD
SCALE = 1.0_JPRD
FAILURES = 0
! Compare the original and recovered arrays in place. cuFFT is unnormalised;
! exclude inactive row padding and reduce once, since ranks have unequal rows.
DO JL=1,D%NDGL_FS
  LATITUDE = D%NPTRLS(MYSETW)+JL-1
  N = G%NLOEN(LATITUDE)
  PITCH = D%NSTAGTF(JL+1)-D%NSTAGTF(JL)
  DO F=1,NFIELDS
    OFFSET = D%NSTAGTF(JL)*NFIELDS+(F-1)*PITCH
    DO J=1,N
      IF (.NOT. IEEE_IS_FINITE(REALSPACE(OFFSET+J)) .OR. &
        & .NOT. IEEE_IS_FINITE(EXPECTED(OFFSET+J))) THEN
        FAILURES = FAILURES+1
      ELSE
        ERROR = MAX(ERROR,ABS(REAL(REALSPACE(OFFSET+J),JPRD)/REAL(N,JPRD)-REAL(EXPECTED(OFFSET+J),JPRD)))
        SCALE = MAX(SCALE,ABS(REAL(EXPECTED(OFFSET+J),JPRD)))
      ENDIF
    ENDDO
  ENDDO
ENDDO
CALL ASSERT_ERROR(ERROR,SCALE,FAILURES,64.0_JPRD*REAL(EPSILON(0.0_JPRB),JPRD),'FFT round-trip identity')
CALL DESTROY_GROWING_ALLOCATOR(STORAGE)
CALL END_TEST('FFT')
END PROGRAM
