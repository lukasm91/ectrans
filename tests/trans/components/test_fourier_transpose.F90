PROGRAM TEST_FOURIER_TRANSPOSE

USE COMPONENT_TEST_UTILS
USE PARKIND_ECTRANS, ONLY: JPRB
USE TPM_DISTR, ONLY: D
USE TRLTOM_MOD, ONLY: PREPARE_TRLTOM, TRLTOM, TRLTOM_HANDLE
USE TRMTOL_MOD, ONLY: PREPARE_TRMTOL, TRMTOL, TRMTOL_HANDLE
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR, MAKE_BUFFERED_ALLOCATOR, INSTANTIATE_ALLOCATOR
USE GROWING_ALLOCATOR_MOD, ONLY: GROWING_ALLOCATION_TYPE, DESTROY_GROWING_ALLOCATOR

IMPLICIT NONE

TYPE(BUFFERED_ALLOCATOR) :: ALLOCATOR
TYPE(GROWING_ALLOCATION_TYPE) :: STORAGE
TYPE(TRLTOM_HANDLE) :: FORWARD
TYPE(TRMTOL_HANDLE) :: BACKWARD
REAL(JPRB), POINTER :: INPUT(:), MSPACE(:), LSPACE(:)
REAL(JPRB), ALLOCATABLE :: EXPECTED(:)

CALL INIT_TEST()
ALLOCATE(INPUT(2*D%NLENGT0B*NFIELDS), EXPECTED(2*D%NLENGT0B*NFIELDS))
CALL RANDOM_VALUES(INPUT)
EXPECTED = INPUT
ALLOCATOR = MAKE_BUFFERED_ALLOCATOR()
NULLIFY(STORAGE%PTR)
STORAGE%FREE_FUNCS_SZ = 0
FORWARD = PREPARE_TRLTOM(ALLOCATOR,NFIELDS)
BACKWARD = PREPARE_TRMTOL(ALLOCATOR,NFIELDS)
CALL INSTANTIATE_ALLOCATOR(ALLOCATOR, STORAGE)
! These two routines only transpose. Packing/hemisphere weighting is separate.
!$ACC DATA COPYIN(INPUT)
CALL TRLTOM(ALLOCATOR,FORWARD,INPUT,MSPACE,NFIELDS)
CALL TRMTOL(ALLOCATOR,BACKWARD,MSPACE,LSPACE,NFIELDS)
!$ACC WAIT(1)
!$ACC UPDATE HOST(LSPACE)
CALL ASSERT_BITS(LSPACE(1:SIZE(EXPECTED)), EXPECTED, 'TRLTOM/TRMTOL bitwise round trip')
!$ACC END DATA
DEALLOCATE(INPUT)
CALL DESTROY_GROWING_ALLOCATOR(STORAGE)
CALL END_TEST('Fourier transpose')
END PROGRAM
